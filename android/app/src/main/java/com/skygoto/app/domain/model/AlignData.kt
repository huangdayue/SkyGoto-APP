/*
 * 文件名：AlignData.kt
 * 描述：星点对齐相关数据模型
 *
 * 定义对齐流程的状态机、对齐星数据、亮星列表等。
 * 对齐流程为 OnStepX 的标准 1~9 星几何对齐。
 */

package com.skygoto.app.domain.model

/**
 * 对齐流程状态机
 *
 * 定义对齐操作的全生命周期状态：
 * - IDLE: 空闲，未进入对齐
 * - HOMING: 正在回零（确保参考零点正确）
 * - STARTING: 正在发送 :A[n]# 启动命令
 * - SELECTING_STAR: 等待用户选择目标星
 * - GOTOING: 望远镜正在 GOTO 到目标星
 * - CENTERING: 用户手动居中目标星（使用方向键）
 * - SYNCING: 正在发送 :CM# 同步
 * - MODEL_BUILDING: OnStepX 正在计算模型参数
 * - COMPLETE: 对齐完成
 * - CANCELLING: 正在取消对齐
 */
enum class AlignState {
    IDLE,
    HOMING,
    STARTING,
    SELECTING_STAR,
    GOTOING,
    CENTERING,
    SYNCING,
    MODEL_BUILDING,
    COMPLETE,
    CANCELLING
}

/**
 * 对齐会话数据
 *
 * 记录一次对齐操作的所有信息。
 *
 * @param state 当前状态
 * @param totalStars 计划对齐的星数（3/6/9）
 * @param currentStarIndex 当前处理的星索引（0-based）
 * @param completedStars 已完成同步的星
 * @param rmsError 完成后模型的 RMS 误差（角秒）
 */
data class AlignSession(
    val state: AlignState = AlignState.IDLE,
    val totalStars: Int = 6,
    val currentStarIndex: Int = 0,
    val completedStars: List<AlignStarSync> = emptyList(),
    val rmsError: Double = 0.0
) {
    /** 已完成星数 */
    val completedCount: Int get() = completedStars.size

    /** 是否所有星都已完成 */
    val isAllCompleted: Boolean get() = completedCount >= totalStars
}

/**
 * 已对齐的星记录
 *
 * @param starData 星体信息
 * @param success 是否同步成功
 * @param message 备注（如误差信息）
 */
data class AlignStarSync(
    val starData: BrightStar,
    val success: Boolean = true,
    val message: String = ""
)

/**
 * 亮星数据（用于对齐选择的推荐星）
 *
 * @param name 星名（中文/英文）
 * @param ra 赤经 HH:MM:SS（J2000 历元）
 * @param dec 赤纬 sDD*MM:SS（J2000 历元）
 * @param magnitude 视星等
 * @param constellation 所在星座
 */
data class BrightStar(
    val name: String,
    val ra: String,
    val dec: String,
    val magnitude: Double,
    val constellation: String = ""
