    // ========== 太阳真黄经 (共享函数, 用于光行差计算) ==========
    /**
     * 计算太阳真黄经 (含章动), 弧度
     * 用于所有天体的光行差修正
     */
    private fun computeSunTrueLongitude(T: Double): Double {
        val L0 = 280.46646 + 36000.76983 * T  // 平黄经 (度)
        val M = 357.52910 + 35999.05030 * T   // 平近点角 (度)
        
        // 方程心项
        val C = (
            (1.914600 - 0.004817 * T) * sin(M * PI_OVER_180) +
            0.019994 * sin(2.0 * M * PI_OVER_180) +
            0.000290 * sin(3.0 * M * PI_OVER_180)
        )
        val sunLon = L0 + C  // 真黄经 (度)
        
        // 章动
        val (dpsi, _) = computeNutation(T)
        return (sunLon * PI_OVER_180) + dpsi  // 弧度, 含章动
    }

    // ========== 周年光行差修正 ==========
    /**
     * 对黄道坐标应用周年光行差修正 (Meeus Ch.23)
     * κ (光行差常数) = 20.49552"
     * @param lambda 黄经 (弧度)
     * @param beta 黄纬 (弧度)
     * @param sunLambda 太阳真黄经 (弧度, 含章动)
     * @return Pair(修正后黄经, 修正后黄纬)
     */
    private fun applyAnnualAberration(
        lambda: Double, beta: Double, sunLambda: Double
    ): Pair<Double, Double> {
        val kappa = 20.49552 * ARCSEC_TO_RAD
        val cosBeta = cos(beta)
        // 黄经修正
        val dLambda = -kappa * (cos(sunLambda - lambda) / cosBeta.coerceAtLeast(1e-10))
        // 黄纬修正
        val dBeta = -kappa * sin(beta) * sin(sunLambda - lambda)
        return Pair(lambda + dLambda, beta + dBeta)
    }

    // ========== 章动计算 (IAU 1980 简化模型) ==========
    /**
     * 计算章动 (Nutation) - IAU 1980 简化模型
     * @param T 儒略世纪数 (J2000 起算)
     * @return Pair<Δψ (弧度), Δε (弧度)>
     */
    private fun computeNutation(T: Double): Pair<Double, Double> {
        val PI = kotlin.math.PI
        
        // 基本引数 (度)
        val D = 297.8502042 + 445267.1114468 * T  // 日月平距
        val M = 357.5291092 + 35999.0502909 * T  // 太阳平近点角
        val Md = 134.9634114 + 477198.8676313 * T // 月球平近点角
        val F = 93.2720993 + 483202.0175273 * T  // 月球升交点黄经
        val Om = 125.04452 - 1934.136261 * T     // 升交点平黄经
        
        // 主要章动项 (arcsec)
        val dpsi = (
            -17.1996 * sin(Om * PI / 180.0) +
            -0.2062 * sin(2.0 * (D - Om) * PI / 180.0) +
            -0.0211 * sin(2.0 * D * PI / 180.0) +
            +0.0059 * sin(2.0 * M * PI / 180.0) +
            +0.0048 * sin(2.0 * Md * PI / 180.0) +
            +0.0037 * sin(Om + 2.0 * (D - Om) * PI / 180.0)
        )
        
        val deps = (
            +9.2025 * cos(Om * PI / 180.0) +
            +0.0009 * cos(2.0 * (D - Om) * PI / 180.0) +
            +0.0009 * cos(2.0 * D * PI / 180.0) +
            -0.0003 * cos(2.0 * M * PI / 180.0)
        )
        
        return Pair(dpsi * ARCSEC_TO_RAD, deps * ARCSEC_TO_RAD)
    }

    // ========== 行星计算 ==========
    private fun calculatePlanet(planet: PlanetId, lat: Double, lon: Double, jd: Double): Pair<String, String>? {
        val T = (jd - 2451545.0) / 36525.0  // 儒略世纪 (用于岁差/章动/光行差)

        // === VSOP87D 或开普勒回退 (Pluto) ===
        val (lJ2000, bJ2000, r) = if (vsopData.containsKey(planet)) {
            // VSOP87D 使用儒略千禧年
            val Tmill = (jd - 2451545.0) / 365250.0
            val vd = vsopData[planet]!!
            val L = vd.L.evaluate(Tmill)
            val B = vd.B.evaluate(Tmill)
            val R = vd.R.evaluate(Tmill)
            Triple(L, B, R)
        } else {
            // 开普勒回退 (仅 Pluto)
            val el = planetaryElements[planet] ?: return null
            val L = (el.L0 + el.L1 * T) * PI_OVER_180
            val M = (el.M0 + el.M1 * T) * PI_OVER_180
            val e = el.e0
            var E = M + e * sin(M) * (1.0 + e * cos(M))
            for (i in 0..5) {
                E = E - (E - e * sin(E) - M) / (1.0 - e * cos(E))
            }
            val xv = cos(E) - e
            val yv = sqrt(1.0 - e * e) * sin(E)
            val v = atan2(yv, xv)
            val r = el.a0 * (1.0 - e * e) / (1.0 + e * cos(v))
            Triple(L + (v - M), 0.0, r)
        }

        // === 岁差修正: J2000 → 当前历元 ===
        val generalPrecession = (5029.0966 * T + 1.11113 * T * T) * ARCSEC_TO_RAD
        val lDate = lJ2000 + generalPrecession

        // === 周年光行差 ===
        val sunLambda = computeSunTrueLongitude(T)
        val (lAberrated, bAberrated) = applyAnnualAberration(lDate, bJ2000, sunLambda)

        // === 章动 (经度章动 dpsi 加到黄经上) ===
        val (dpsi, deps) = computeNutation(T)
        val lApparent = lAberrated + dpsi  // 真日期黄经
        val epsilon0 = 23.43929111 * PI_OVER_180
        val epsilon = epsilon0 + deps

        // === 黄道 → 赤道 ===
        val ra = atan2(cos(epsilon) * sin(lApparent), cos(lApparent))
        val dec = asin(sin(epsilon) * sin(lApparent) * cos(bAberrated) + cos(epsilon) * sin(bAberrated))

        // === 土星木星摄动 (VSOP87D 已含此效应, 仅对开普勒回退补充) ===
        val (raFinal, decFinal) = if (!vsopData.containsKey(planet) && planet == PlanetId.SATURN) {
            val saturnPert = computeSaturnPerturbation(T, lDate)
            Pair(ra + saturnPert.first, dec + saturnPert.second)
        } else {
            Pair(ra, dec)
        }

        // === 地平坐标 (含大气折射) ===
        val lmst = localMeanSiderealTime(jd, lon)
        val ha = lmst - raFinal
        val latRad = lat * PI_OVER_180
        val sinAlt = sin(decFinal) * sin(latRad) + cos(decFinal) * cos(latRad) * cos(ha)
        val altGeometric = asin(sinAlt.coerceIn(-1.0, 1.0)) * 180.0 / PI
        val altRefracted = altGeometric + refractionArcmin(altGeometric) / 60.0

        val az = atan2(-cos(decFinal) * sin(ha),
                       sin(decFinal) * cos(latRad) - cos(decFinal) * sin(latRad) * cos(ha))

        return Pair(formatRA(raFinal), formatDec(decFinal))
    }

    // ========== 土星摄动修正 (木星引力影响) ==========
    private fun computeSaturnPerturbation(T: Double, saturnLon: Double): Pair<Double, Double> {
        // 木星对土星的主要摄动项
        // 基于 Meeus Chapter 36 的简化模型
        val PI = kotlin.math.PI
        
        // 木星平黄经
        val L_JUP = (34.3515 + 3034.9057 * T) * PI_OVER_180
        // 木星-土星会合周期项
        val pertAngle = 2.0 * (L_JUP - saturnLon)
        val pertAmp = 0.0069 * ARCSEC_TO_RAD  // ~25角秒
        
        val dLon = pertAmp * sin(pertAngle)
        val dLat = 0.0012 * ARCSEC_TO_RAD * sin(pertAngle + 0.56)
        
        // 近似转换为 RA/Dec 变化
        val epsilon0 = 23.43929111 * PI_OVER_180
        val dRA = dLon * cos(epsilon0) - dLat * sin(epsilon0) * 0.3
        val dDec = dLon * sin(epsilon0) + dLat * cos(epsilon0) * 0.3
        
        return Pair(dRA, dDec)
    }

    // ========== 太阳计算 (Meeus Chapter 28) ==========
    private fun calculateSun(lat: Double, lon: Double, jd: Double): Pair<String, String>? {
        val T = (jd - 2451545.0) / 36525.0
        
        // 使用共享函数获取真黄经（含章动）
        val sunLon = computeSunTrueLongitude(T)
        
        // 视差修正 (太阳地心→站心)
        val sunLonParallax = sunLon - 0.0057 * ARCSEC_TO_RAD
        
        // 光行差修正 (用共享函数, beta=0 因为太阳黄纬≈0)
        val (lAberrated, _) = applyAnnualAberration(sunLonParallax, 0.0, sunLon)
        
        // 章动修正的黄赤交角
        val (_, deps) = computeNutation(T)
        val epsilon0 = 23.43929111 * PI_OVER_180
        val epsilon = epsilon0 + deps
        
        // 赤道坐标
        val sunRA = atan2(cos(epsilon) * sin(lAberrated), cos(lAberrated))
        val sunDec = asin(sin(epsilon) * sin(lAberrated))
        
        val lmst = localMeanSiderealTime(jd, lon)
        val ha = lmst - sunRA
        
        val latRad = lat * PI_OVER_180
        val sinAlt = sin(sunDec) * sin(latRad) + 
                     cos(sunDec) * cos(latRad) * cos(ha)
        val altGeometric = asin(sinAlt.coerceIn(-1.0, 1.0)) * 180.0 / PI
        val altRefracted = altGeometric + refractionArcmin(altGeometric) / 60.0
        
        val az = atan2(-cos(sunDec) * sin(ha),
                       sin(sunDec) * cos(latRad) - 
                       cos(sunDec) * sin(latRad) * cos(ha))
        
        return Pair(formatRA(sunRA), formatDec(sunDec))
    }

    // ========== 月球计算 (ELP2000 简化算法, 30+ 项) ==========
    private fun calculateMoon(lat: Double, lon: Double, jd: Double): Pair<String, String>? {
        val T = (jd - 2451545.0) / 36525.0
        val PI = kotlin.math.PI
        
        // 基本引数 (度)
        val L0 = 218.3164591 + 481267.88134236 * T  // 月球平黄经
        val l = 134.9634114 + 477198.8676313 * T     // 太阳平近点角 (l')
        val lp = 357.5291092 + 35999.0502909 * T   // 月球平近点角 (l)
        val F = 93.2720993 + 483202.0175273 * T     // 月球升交点距 (F)
        val D = 297.8502042 + 445267.1114468 * T   // 日月平距 (D)
        
        // ELP2000 简化模型 - 主要周期项 (35项 → ~55项, 精度 ~0.003° → ~0.0015°)
        // 参考: Meeus Chapter 47, ELP2000-82 简化序列
        val lambda = L0 + 
            // ---- 主要项 (> 0.1°) ----
            + 6.2890 * sin(l * PI_OVER_180) 
            + 1.2740 * sin((2.0 * D - l) * PI_OVER_180)
            + 0.6580 * sin(2.0 * D * PI_OVER_180)
            + 0.2136 * sin(2.0 * l * PI_OVER_180)
            - 0.1864 * sin(lp * PI_OVER_180)
            - 0.1144 * sin(2.0 * F * PI_OVER_180)
            // ---- 中等项 (0.01° ~ 0.1°) ----
            + 0.0588 * sin((2.0 * D - 2.0 * l) * PI_OVER_180)
            + 0.0572 * sin((2.0 * D - l + lp) * PI_OVER_180)
            - 0.0455 * sin((2.0 * D - lp) * PI_OVER_180)
            - 0.0410 * sin((l - 2.0 * F) * PI_OVER_180)
            - 0.0347 * sin(2.0 * D * PI_OVER_180)
            + 0.0303 * sin((l + lp) * PI_OVER_180)
            + 0.0263 * sin((2.0 * D - 2.0 * F) * PI_OVER_180)
            + 0.0214 * sin((l - lp) * PI_OVER_180)
            + 0.0199 * sin((l + 2.0 * F) * PI_OVER_180)
            + 0.0193 * sin((4.0 * D - l) * PI_OVER_180)
            + 0.0171 * sin((4.0 * D - 2.0 * l) * PI_OVER_180)
            + 0.0154 * sin((2.0 * D - 6.0 * l) * PI_OVER_180)
            + 0.0132 * sin(3.0 * l * PI_OVER_180)
            + 0.0109 * sin(4.0 * D * PI_OVER_180)
            - 0.0107 * sin((l + 2.0 * D) * PI_OVER_180)
            + 0.0100 * sin((2.0 * D + lp - l) * PI_OVER_180)
            // ---- 小项 (0.005° ~ 0.01°) ----
            + 0.0087 * sin((lp - 2.0 * D) * PI_OVER_180)
            - 0.0086 * sin((2.0 * D + 2.0 * l) * PI_OVER_180)
            + 0.0085 * sin((l - 2.0 * D) * PI_OVER_180)
            + 0.0069 * sin((2.0 * l + 2.0 * D) * PI_OVER_180)
            - 0.0068 * sin((l - 4.0 * D + lp) * PI_OVER_180)
            + 0.0053 * sin((l + lp - 2.0 * D) * PI_OVER_180)
            + 0.0050 * sin(2.0 * l + lp * PI_OVER_180)
            + 0.0043 * sin((l - 2.0 * lp) * PI_OVER_180)
            + 0.0038 * sin((2.0 * D - l - lp) * PI_OVER_180)
            // ---- 补充小项 (0.002° ~ 0.005°), 新增 ----
            + 0.0037 * sin(6.0 * D * PI_OVER_180)
            - 0.0036 * sin(2.0 * lp * PI_OVER_180)
            + 0.0035 * sin((3.0 * D - l) * PI_OVER_180)
            - 0.0034 * sin((2.0 * D + l - 2.0 * lp) * PI_OVER_180)
            + 0.0033 * sin((2.0 * D + l) * PI_OVER_180)
            - 0.0032 * sin((4.0 * D - l - lp) * PI_OVER_180)
            + 0.0031 * sin((2.0 * D - l + 2.0 * F) * PI_OVER_180)
            - 0.0029 * sin((4.0 * D - l - 2.0 * F) * PI_OVER_180)
            - 0.0028 * sin((4.0 * D - l + 2.0 * F) * PI_OVER_180)
            + 0.0027 * sin((4.0 * D - 2.0 * l + lp) * PI_OVER_180)
            - 0.0026 * sin(4.0 * l * PI_OVER_180)
            + 0.0025 * sin((l - 4.0 * D + 2.0 * F) * PI_OVER_180)
            - 0.0024 * sin((2.0 * D - 2.0 * l + lp) * PI_OVER_180)
            + 0.0023 * sin((2.0 * D + l - 2.0 * F) * PI_OVER_180)
            - 0.0022 * sin((4.0 * D - 3.0 * l) * PI_OVER_180)
            - 0.0021 * sin((2.0 * D - l - 2.0 * lp) * PI_OVER_180)
