    // ========== VSOP87D 行星理论 (取代开普勒轨道) ==========
    // VSOP87D 直接输出 J2000 黄道球坐标 (L, B, R), 精度 ~0.001°

    /** VSOP87D 周期项: A·cos(B + C·T), 结果弧度(L/B)或AU(R) */
    private data class VSOPTerm(val A: Double, val B: Double, val C: Double)

    /** VSOP87D 系列: 按 T 幂次分组的周期项列表 */
    private class VSOPSeries(vararg val groups: List<VSOPTerm>) {
        fun evaluate(T: Double): Double {
            var result = 0.0
            var Tpow = 1.0
            for (terms in groups) {
                var sum = 0.0
                for (t in terms) {
                    sum += t.A * cos(t.B + t.C * T)
                }
                result += sum * Tpow
                Tpow *= T
            }
            return result
        }
    }

