            - 0.0049 * sin((4.0 * D - F) * PI_OVER_180)
            - 0.0043 * sin((4.0 * D + F) * PI_OVER_180)
            + 0.0039 * sin((4.0 * D - l - F) * PI_OVER_180)
            + 0.0035 * sin((4.0 * D + l + F) * PI_OVER_180)
            - 0.0032 * sin((4.0 * D - l + F) * PI_OVER_180)
            + 0.0029 * sin((2.0 * l + 2.0 * F) * PI_OVER_180)
            - 0.0026 * sin((4.0 * D + l - F) * PI_OVER_180)
            - 0.0024 * sin((2.0 * D + 2.0 * l - F) * PI_OVER_180)
            + 0.0021 * sin((2.0 * D - l - F) * PI_OVER_180)
            - 0.0019 * sin((4.0 * D - 2.0 * l + F) * PI_OVER_180)
